def get_trader_detail(address: str) -> TraderDetail | None:
    for trader in TRADERS:
        if trader.address == address:
            recent = [
                a for a in WHALE_ALERTS if a.trader_address == address
            ][:5]
            positions = [
                {
                    "asset": a.asset,
                    "side": a.side.value,
                    "type": a.alert_type.value,
                    "size_usd": a.size_usd,
                    "price": a.entry_price or a.exit_price,
                    "timestamp": a.timestamp.isoformat(),
                }
                for a in recent
            ]
            return TraderDetail(
                **trader.model_dump(),
                recent_positions=positions,
                behavior_summary=(
                    f"{trader.alias} is a {trader.strategy_tags[0].lower()} trader "
                    f"with {trader.win_rate}% win rate over {trader.total_trades} trades. "
                    f"Prefers {', '.join(trader.preferred_assets)} with avg hold time "
                    f"of {trader.avg_hold_hours}h."
                ),
            )
    return None
